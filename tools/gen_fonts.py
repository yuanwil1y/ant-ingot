#!/usr/bin/env python3
"""Rasterise the ingot's fonts into 4-bit anti-aliased C tables.

Output: main/core/fonts.c + fonts.h. Run from the repo root:
    python3 tools/gen_fonts.py
"""
import os
from PIL import ImageFont, Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "fonts-src")
ASCII = "".join(chr(c) for c in range(32, 127))
DIGITS = " 0123456789$.,%+-x"

# name, file, px size, weight (variable axis) or None, charset
FONTS = [
    ("caps11", "Cinzel[wght].ttf", 11, 700, ASCII),
    ("caps13", "Cinzel[wght].ttf", 13, 700, ASCII),
    ("caps18", "Cinzel[wght].ttf", 18, 700, ASCII),
    ("caps26", "Cinzel[wght].ttf", 26, 700, ASCII),
    ("caps64", "Cinzel[wght].ttf", 64, 600, " 0123456789ANT"),
    ("ital17", "EBGaramond-Italic[wght].ttf", 17, 500, ASCII),
    ("serif13", "EBGaramond[wght].ttf", 13, 500, ASCII),
    ("mono11", "IBMPlexMono-Medium.ttf", 11, None, ASCII),
    ("mono14", "IBMPlexMono-Medium.ttf", 14, None, ASCII),
    ("mono32", "IBMPlexMono-Medium.ttf", 32, None, DIGITS),
]


def load(file, size, wght):
    f = ImageFont.truetype(os.path.join(SRC, file), size)
    if wght is not None:
        try:
            f.set_variation_by_axes([wght])
        except Exception as e:  # static font
            print("no variation for", file, e)
    return f


def build(name, file, size, wght, chars):
    font = load(file, size, wght)
    ascent, descent = font.getmetrics()
    glyphs = {}
    data = bytearray()
    for ch in chars:
        adv = font.getlength(ch)
        bbox = font.getbbox(ch, anchor="ls")
        x0, y0, x1, y1 = bbox
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h and ch != " ":
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = list(im.getdata())
            nib = [min(15, (p * 15 + 127) // 255) for p in px]
            if len(nib) % 2:
                nib.append(0)
            for i in range(0, len(nib), 2):
                data.append((nib[i] << 4) | nib[i + 1])
        else:
            w = h = 0
        glyphs[ord(ch)] = (off, w, h, x0, y0, int(round(adv * 16)))
    return ascent, descent, glyphs, data


def main():
    out_c = ["/* generated by tools/gen_fonts.py — do not edit */", '#include "fonts.h"', ""]
    out_h = ["/* generated by tools/gen_fonts.py — do not edit */", "#pragma once", '#include "gfx.h"', ""]
    for name, file, size, wght, chars in FONTS:
        asc, desc, glyphs, data = build(name, file, size, wght, chars)
        out_c.append(f"static const uint8_t {name}_bits[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            out_c.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        if not data:
            out_c.append("  0")
        out_c.append("};")
        out_c.append(f"static const glyph_t {name}_glyphs[95] = {{")
        for c in range(32, 127):
            if c in glyphs:
                off, w, h, xo, yo, adv = glyphs[c]
                out_c.append(f"  {{{off},{w},{h},{xo},{yo},{adv}}}, /* {chr(c)!r} */")
            else:
                out_c.append("  {0,0,0,0,0,0},")
        out_c.append("};")
        out_c.append(f"const font_t font_{name} = {{ {name}_bits, {name}_glyphs, {asc}, {desc} }};")
        out_c.append("")
        out_h.append(f"extern const font_t font_{name};")
        print(f"{name}: {len(data)} bytes, ascent {asc}, descent {desc}")
    with open(os.path.join(ROOT, "main/core/fonts.c"), "w") as f:
        f.write("\n".join(out_c) + "\n")
    with open(os.path.join(ROOT, "main/core/fonts.h"), "w") as f:
        f.write("\n".join(out_h) + "\n")


if __name__ == "__main__":
    main()
